// Inlines the built mini app and the guide data into worker/index.js,
// the module that worker/worker.js imports at the edge.
import { readFileSync, writeFileSync } from 'node:fs';
import { transformSync } from 'esbuild';

let html = readFileSync('miniapp/dist/index.html', 'utf8');

// KaTeX ships 20 faces in woff2 + woff + ttf; the page only ever needs woff2.
// Drop the legacy copies and serve the rest from /katex (static assets) so the
// HTML stays small and the browser downloads a font only when it is used.
html = html.replace(/data:font\/woff;base64,[A-Za-z0-9+/=]+|data:font\/ttf;base64,[A-Za-z0-9+/=]+/g, 'about:blank');
html = html.replace(/url\(data:font\/woff2;base64,[A-Za-z0-9+/=]+\)/g, (m, off, all) => m);

// Self-host the Telegram bridge: telegram.org is filtered in some networks.
const SELF_HOSTED_BRIDGE = '/telegram-web-app.js';

// miniapp/src/content.ts has no external imports, so it can be transpiled and
// executed standalone to pull out the plain data arrays it exports.
const ts = readFileSync('miniapp/src/content.ts', 'utf8');
const { code } = transformSync(ts, { loader: 'ts', format: 'cjs' });
const mod = { exports: {} };
new Function('module', 'exports', code)(mod, mod.exports);
const { GUIDES, RELEASES } = mod.exports;

// Rewrite the inlined woff2 blobs to the self-hosted static files.
const fontNames = [...html.matchAll(/data:font\/woff2;base64,([A-Za-z0-9+/=]+)/g)];
const order = ['KaTeX_AMS-Regular','KaTeX_Caligraphic-Bold','KaTeX_Caligraphic-Regular','KaTeX_Fraktur-Bold','KaTeX_Fraktur-Regular','KaTeX_Main-Bold','KaTeX_Main-BoldItalic','KaTeX_Main-Italic','KaTeX_Main-Regular','KaTeX_Math-BoldItalic','KaTeX_Math-Italic','KaTeX_SansSerif-Bold','KaTeX_SansSerif-Italic','KaTeX_SansSerif-Regular','KaTeX_Script-Regular','KaTeX_Size1-Regular','KaTeX_Size2-Regular','KaTeX_Size3-Regular','KaTeX_Size4-Regular','KaTeX_Typewriter-Regular'];
let n = 0;
html = html.replace(/url\(data:font\/woff2;base64,[A-Za-z0-9+/=]+\)/g, () => {
  const name = order[n++] || order[order.length - 1];
  return `url(/katex/fonts/${name}.woff2)`;
});
if (n !== fontNames.length) console.warn(`font rewrite: ${n}/${fontNames.length} faces mapped`);

const out = `// Auto-generated by tools/build-worker.mjs — do not edit by hand.
export const guides = ${JSON.stringify(GUIDES)};
export const releases = ${JSON.stringify(RELEASES)};
export default ${JSON.stringify(html.replaceAll('https://telegram.org/js/telegram-web-app.js', SELF_HOSTED_BRIDGE))};
`;

writeFileSync('worker/index.js', out);
console.log(`Generated worker/index.js (${(out.length / 1024).toFixed(0)} KB)`);

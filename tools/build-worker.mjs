// Inlines the built mini app and the guide data into worker/index.js,
// the module that worker/worker.js imports at the edge.
import { readFileSync, writeFileSync } from 'node:fs';
import { transformSync } from 'esbuild';

const html = readFileSync('miniapp/dist/index.html', 'utf8');

// Self-host the Telegram bridge: telegram.org is filtered in some networks.
const SELF_HOSTED_BRIDGE = '/telegram-web-app.js';

// miniapp/src/content.ts has no external imports, so it can be transpiled and
// executed standalone to pull out the plain data arrays it exports.
const ts = readFileSync('miniapp/src/content.ts', 'utf8');
const { code } = transformSync(ts, { loader: 'ts', format: 'cjs' });
const mod = { exports: {} };
new Function('module', 'exports', code)(mod, mod.exports);
const { GUIDES, RELEASES } = mod.exports;

const out = `// Auto-generated by tools/build-worker.mjs — do not edit by hand.
export const guides = ${JSON.stringify(GUIDES)};
export const releases = ${JSON.stringify(RELEASES)};
export default ${JSON.stringify(html.replaceAll('https://telegram.org/js/telegram-web-app.js', SELF_HOSTED_BRIDGE))};
`;

writeFileSync('worker/index.js', out);
console.log(`Generated worker/index.js (${(out.length / 1024).toFixed(0)} KB)`);
